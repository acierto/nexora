func items() []knowledge.Item {
	rule := func(id string, required bool, paths, agents []string) knowledge.Item {
		return knowledge.Item{ID: id, Name: "Rule " + id, Description: "About " + id, Kind: knowledge.Rule, Content: "Content of " + id + ".\n", Version: "1", Status: knowledge.Active, Required: required,
			AppliesTo: knowledge.Applicability{Projects: []string{"shop"}, Paths: paths, Agents: agents}, Source: knowledge.Source{ID: "local", Path: id + ".md"}}
	}
	skill := knowledge.Item{ID: "skills/add-endpoint", Name: "Add an endpoint", Description: "Procedure: add an endpoint", Kind: knowledge.Skill, Content: "1. Define types.\n", Version: "2", Status: knowledge.Active, Source: knowledge.Source{ID: "local", Path: "skills/add-endpoint/SKILL.md"}}
	archived := rule("old/rule", true, nil, nil)
	archived.Status = knowledge.Archived
	return []knowledge.Item{
		rule("go/conventions", true, nil, nil),
		rule("security/auth", true, []string{"src/auth/**/*.go"}, nil),
		rule("go/naming", false, nil, nil),
		rule("agents/claude", true, nil, []string{"claude"}),
		archived,
		skill,
	}
}

func TestSyncPreservesAndIsIdempotent(t *testing.T) {
	dir := t.TempDir()
	original := "# Project rules\n\nHand-written guidance.\n"
	if err := os.WriteFile(filepath.Join(dir, "AGENTS.md"), []byte(original), 0o644); err != nil {
		t.Fatal(err)
	}
	opt := Options{Agent: "codex", Project: "shop", Dir: dir, Items: items()}
	plan, err := Plan(opt)
	if err != nil {
		t.Fatal(err)
	}
	if err := Apply(dir, plan); err != nil {
		t.Fatal(err)
	}
	data, _ := os.ReadFile(filepath.Join(dir, "AGENTS.md"))
	text := string(data)
	if !strings.HasPrefix(text, original+"\n"+Begin) || !strings.HasSuffix(text, End+"\n") {
		t.Fatalf("original text not preserved:\n%s", text)
	}
	for _, want := range []string{"### Always apply", "`go/conventions`", "### When you change matching files", "`src/auth/**/*.go`", "### Optional guidance", "`go/naming`", "`add-endpoint`", "nexora resolve --agent codex"} {
		if !strings.Contains(text, want) {
			t.Fatalf("missing %q in:\n%s", want, text)
		}
	}
	for _, unwanted := range []string{"agents/claude", "old/rule"} {
		if strings.Contains(text, unwanted) {
			t.Fatalf("%s should not be synced for codex", unwanted)
		}
	}
	skill, err := os.ReadFile(filepath.Join(dir, ".agents", "skills", "add-endpoint", "SKILL.md"))
	if err != nil || !strings.HasPrefix(string(skill), "---\nname: add-endpoint\ndescription: \"Procedure: add an endpoint\"\n---\n") {
		t.Fatalf("skill: %q %v", skill, err)
	}
	plan, err = Plan(opt)
	if err != nil || plan.Changed() || len(plan.Conflicts) > 0 {
		t.Fatalf("second plan should be a no-op: %+v %v", plan, err)
	}
	// Edits outside the block survive regeneration.
	edited := strings.Replace(text, "Hand-written guidance.", "Hand-written guidance, edited.", 1) + "\nTrailing notes.\n"
	os.WriteFile(filepath.Join(dir, "AGENTS.md"), []byte(edited), 0o644)
	plan, _ = Plan(opt)
	if plan.Changed() {
		t.Fatalf("edits outside the block must not trigger changes: %+v", plan.Changes)
	}
}

func TestSyncConflictsAndStaleSkills(t *testing.T) {
	dir := t.TempDir()
	opt := Options{Agent: "claude", Project: "shop", Dir: dir, Items: items()}
	plan, _ := Plan(opt)
	if err := Apply(dir, plan); err != nil {
		t.Fatal(err)
	}
	claude, _ := os.ReadFile(filepath.Join(dir, "CLAUDE.md"))
	if !strings.Contains(string(claude), "agents/claude") {
		t.Fatal("claude-specific rule missing")
	}
	skillFile := filepath.Join(dir, ".claude", "skills", "add-endpoint", "SKILL.md")
	os.WriteFile(skillFile, []byte("my edit\n"), 0o644)
	plan, _ = Plan(opt)
	if len(plan.Conflicts) != 1 || Apply(dir, plan) == nil {
		t.Fatalf("manual edit must stop the sync: %+v", plan.Conflicts)
	}
	if data, _ := os.ReadFile(skillFile); string(data) != "my edit\n" {
		t.Fatal("conflicting file was overwritten")
	}
	// Restore, then remove the skill from knowledge: the generated file goes away.
	os.Remove(skillFile)
	plan, _ = Plan(opt)
	Apply(dir, plan)
	withoutSkill := items()[:5]
	plan, _ = Plan(Options{Agent: "claude", Project: "shop", Dir: dir, Items: withoutSkill})
	if err := Apply(dir, plan); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(skillFile); !os.IsNotExist(err) {
		t.Fatal("stale generated skill not removed")
	}
	// A pre-existing, untracked skill file with the same name is a conflict.
	other := t.TempDir()
	os.MkdirAll(filepath.Join(other, ".claude", "skills", "add-endpoint"), 0o755)
	os.WriteFile(filepath.Join(other, ".claude", "skills", "add-endpoint", "SKILL.md"), []byte("mine"), 0o644)
	plan, _ = Plan(Options{Agent: "claude", Project: "shop", Dir: other, Items: items()})
	if len(plan.Conflicts) != 1 || !strings.Contains(plan.Conflicts[0], "not generated by nexora") {
		t.Fatalf("untracked file conflict: %+v", plan.Conflicts)
	}
	// Broken markers are reported, not repaired.
	os.WriteFile(filepath.Join(other, "CLAUDE.md"), []byte(Begin+"\nno end\n"), 0o644)
	if _, err := Plan(Options{Agent: "claude", Project: "shop", Dir: other, Items: items()}); err == nil {
		t.Fatal("unterminated block accepted")
	}
}

func TestSkillName(t *testing.T) {
	for id, want := range map[string]string{"skills/add-endpoint": "add-endpoint", "payments/Refund_Flow.v2": "payments-refund-flow-v2", "skills/" + strings.Repeat("a", 80): strings.Repeat("a", 64)} {
		if got := SkillName(id); got != want {
			t.Fatalf("%s: %s", id, got)
		}
	}
}
